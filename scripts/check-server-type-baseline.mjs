#!/usr/bin/env node
// Test-inclusive TypeScript non-regression gate for apps/server (default) and
// apps/web (`--project web`, KID-209). Next's build type-check filters spec
// diagnostics out, so apps/web specs have the same gap the server note below
// describes; the web project also ignores generated `.next/` type files.
//
// Why this exists
//   The server build type-checks with `apps/server/tsconfig.build.json`, which
//   EXCLUDES `*.spec.ts` and `src/**/__tests__/`. vitest runs specs through
//   esbuild and does not type-check them either. So nothing type-checks the
//   test sources: a changed constructor or port signature can leave every spec
//   construction site broken while every gate stays green.
//
//   This gate type-checks apps/server with the test-inclusive
//   `apps/server/tsconfig.json`, counts errors per file, and compares against
//   the ceiling recorded in scripts/.server-type-baseline.txt. It does NOT
//   require the pre-existing errors to be fixed first.
//
// Policy
//   current count >  baseline count  -> FAIL (regression)
//   current count <= baseline count  -> PASS (fixes tolerated)
//   file in current, NOT in baseline -> FAIL (new/renamed file has errors)
//   file in baseline, NOT in current -> PASS (baseline entry decayed; OK)
//
// Removal tolerance
//   The baseline is a ceiling, not a floor. Clean-up PRs that fix existing
//   errors land without coordinating a baseline edit, and their drops surface
//   as a non-failing "ratchet hint" until the baseline is regenerated.
//
// Regenerate the baseline (after a legitimate ratchet):
//   node scripts/check-server-type-baseline.mjs --regenerate
//
// Runtime: ~17s. `--incremental false` is deliberate — the gate must not read
// or write apps/server/dist/tsconfig.tsbuildinfo, because a gate that can pass
// from a stale cache is not a gate.
//
// Implemented as .mjs, not .sh, because the work is spawn-and-parse: it has to
// tolerate tsc's non-zero exit, group ~400 diagnostic lines by path, and do
// ~110 baseline lookups. Bash 3.2 (the macOS default, and the constraint
// check-shared-root-imports.sh works around) has no associative arrays, so
// those lookups would be an O(n^2) linear scan.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const require = createRequire(import.meta.url);
const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..');
const PROJECTS = {
  server: {
    tsconfig: 'apps/server/tsconfig.json',
    baselineFile: 'scripts/.server-type-baseline.txt',
    npmScript: 'check:server-type-baseline',
    ignore: [],
    note: `    - The build config (tsconfig.build.json) excludes specs and __tests__, and
      vitest does not type-check. This gate is the only thing that type-checks
      apps/server test sources, so a failure here is usually real: a signature
      changed and its spec construction sites were not updated.`,
  },
  web: {
    tsconfig: 'apps/web/tsconfig.json',
    baselineFile: 'scripts/.web-type-baseline.txt',
    npmScript: 'check:web-type-baseline',
    // Generated by \`next build\`/\`next dev\`; present only in some checkouts.
    ignore: [/(^|\/)\.next\//],
    note: `    - \`next build\` filters spec diagnostics out of its type-check, and vitest
      does not type-check. This gate is the only thing that type-checks
      apps/web test sources, so a failure here is usually real: a prop or
      contract changed and its spec fixtures were not updated.`,
  },
};

export function resolveTypeBaselineProject(name) {
  const project = PROJECTS[name];
  if (!project) {
    throw new Error(`unknown project "${name}" (expected ${Object.keys(PROJECTS).join(' or ')})`);
  }
  return {
    name,
    tsconfig: project.tsconfig,
    baselineFile: project.baselineFile,
    npmScript: project.npmScript,
  };
}

function regenerateCommand(name) {
  return `node scripts/check-server-type-baseline.mjs${name === 'server' ? '' : ` --project ${name}`} --regenerate`;
}

function baselineHeader(name) {
  const project = PROJECTS[name];
  return `# ${project.baselineFile}
#
# apps/${name} type-error ceiling: per-file count of TypeScript diagnostics
# produced by \`tsc -p ${project.tsconfig} --noEmit\`, the TEST-INCLUSIVE config.
# Generated by \`${regenerateCommand(name)}\`.
#
# Removal-tolerant: a file whose count drops, or that leaves the scan entirely,
# does NOT require a regeneration to keep the gate green. Regenerate only when
# ratcheting the ceiling down.
#
# Format per non-comment line: <count> <repo-relative-path>`;
}

// `src/path/file.ts(12,34): error TS2554: Expected 3 arguments, but got 2.`
// Continuation lines of a multi-line diagnostic are indented and do not match.
const ERROR_LINE = /^(.*?)\((\d+),(\d+)\):\s+error\s+TS\d+:/;
// Project-level diagnostics carry no file position, e.g.
// `error TS18003: No inputs were found in config file ...`. Those mean the
// harness is misconfigured, not that source code regressed.
const PROJECT_LEVEL_ERROR = /^error\s+TS\d+:/;
// tsc should not colourise a piped stream, but --pretty false plus this strip
// keeps parsing independent of terminal detection.
const ANSI = /\u001B\[[0-9;]*m/g;

function toRepoRelative(filePath, repoRoot) {
  const normalized = filePath.trim();
  if (!path.isAbsolute(normalized)) return normalized.split(path.sep).join('/');
  return path.relative(repoRoot, normalized).split(path.sep).join('/');
}

/**
 * Groups tsc `--pretty false` output by file. `ignore` drops diagnostics whose
 * repo-relative path matches (generated files). Project-level diagnostics are
 * returned separately: they mean the harness is misconfigured.
 */
export function parseTscDiagnostics(output, { repoRoot, ignore = [] }) {
  const counts = new Map();
  const projectErrors = [];
  for (const line of output.replace(ANSI, '').split('\n')) {
    if (PROJECT_LEVEL_ERROR.test(line)) {
      projectErrors.push(line.trim());
      continue;
    }
    const match = ERROR_LINE.exec(line);
    if (!match) continue;
    const rel = toRepoRelative(match[1], repoRoot);
    if (!rel || ignore.some((pattern) => pattern.test(rel))) continue;
    counts.set(rel, (counts.get(rel) ?? 0) + 1);
  }
  return { counts, projectErrors };
}

/** New files with errors and files above their ceiling; decay is tolerated. */
export function compareToBaseline({ baseline, current }) {
  const newFiles = [];
  const grownFiles = [];
  for (const [rel, count] of current) {
    const allowed = baseline.get(rel);
    if (allowed === undefined) {
      newFiles.push(`${count} ${rel}`);
    } else if (count > allowed) {
      grownFiles.push(`${rel}: ${allowed} -> ${count}`);
    }
  }
  return { newFiles, grownFiles };
}

// Run the test-inclusive project and return a Map of
// repo-relative path -> error count.
function computeCurrentCounts(name) {
  const project = PROJECTS[name];
  let tscEntry;
  try {
    // Each workspace owns its compiler; the server may upgrade before the web.
    tscEntry = require.resolve('typescript/bin/tsc', {
      paths: [path.dirname(path.resolve(REPO_ROOT, project.tsconfig))],
    });
  } catch {
    console.error('ERROR: typescript is not installed. Run `npm install` first.');
    process.exit(2);
  }

  const result = spawnSync(
    process.execPath,
    [tscEntry, '-p', project.tsconfig, '--noEmit', '--pretty', 'false', '--incremental', 'false'],
    { cwd: REPO_ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  );

  if (result.error) {
    console.error(`ERROR: failed to run tsc: ${result.error.message}`);
    process.exit(2);
  }

  // A non-zero exit is the EXPECTED outcome here — type errors are the input,
  // not a failure. Only a non-zero exit with nothing parseable is a real crash.
  const output = `${result.stdout ?? ''}\n${result.stderr ?? ''}`;
  const { counts, projectErrors } = parseTscDiagnostics(output, {
    repoRoot: REPO_ROOT,
    ignore: project.ignore,
  });

  if (projectErrors.length > 0) {
    console.error(`ERROR: tsc reported project-level problems with ${project.tsconfig}:`);
    for (const problem of projectErrors) console.error(`  ${problem}`);
    process.exit(2);
  }

  if (counts.size === 0 && result.status !== 0) {
    console.error(`ERROR: tsc exited ${result.status} without emitting any parseable diagnostic.`);
    console.error(output.replace(ANSI, '').trim().slice(0, 4000));
    process.exit(2);
  }

  return counts;
}

// Sorted by path so the generated file has a stable diff.
function sortedEntries(counts) {
  return [...counts.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

function totalOf(entries) {
  return entries.reduce((sum, [, count]) => sum + count, 0);
}

function readBaseline(name) {
  const baselineFile = path.join(REPO_ROOT, PROJECTS[name].baselineFile);
  if (!existsSync(baselineFile)) {
    console.error(`ERROR: baseline file not found: ${baselineFile}`);
    console.error(`  Generate with: ${regenerateCommand(name)}`);
    process.exit(2);
  }

  const baseline = new Map();
  for (const raw of readFileSync(baselineFile, 'utf8').split('\n')) {
    const trimmed = raw.trim();
    if (trimmed === '' || trimmed.startsWith('#')) continue;
    const separator = trimmed.search(/\s/);
    const countPart = separator === -1 ? trimmed : trimmed.slice(0, separator);
    const pathPart = separator === -1 ? '' : trimmed.slice(separator).trim();
    if (!/^\d+$/.test(countPart)) {
      console.error(`ERROR: malformed baseline line (count not numeric): ${raw}`);
      process.exit(2);
    }
    if (pathPart === '') {
      console.error(`ERROR: malformed baseline line (missing path): ${raw}`);
      process.exit(2);
    }
    baseline.set(pathPart, Number(countPart));
  }
  return baseline;
}

function regenerate(name) {
  const project = PROJECTS[name];
  const baselineFile = path.join(REPO_ROOT, project.baselineFile);
  console.log(`${project.npmScript} - regenerating from ${project.tsconfig} ...`);
  const entries = sortedEntries(computeCurrentCounts(name));
  const body = entries.map(([rel, count]) => `${count} ${rel}`).join('\n');
  writeFileSync(baselineFile, `${baselineHeader(name)}\n${body}${body ? '\n' : ''}`, 'utf8');
  console.log(`baseline written: ${baselineFile}`);
  console.log(`   ${entries.length} file entries`);
  console.log(`   ${totalOf(entries)} type error(s)`);
}

function verify(name) {
  const project = PROJECTS[name];
  console.log(`${project.npmScript} - type-checking ${project.tsconfig} (test-inclusive, ~17s)`);
  const baseline = readBaseline(name);
  const current = sortedEntries(computeCurrentCounts(name));
  const { newFiles, grownFiles } = compareToBaseline({ baseline, current: new Map(current) });

  const baselineEntries = [...baseline.entries()];
  const totalBaseline = totalOf(baselineEntries);
  const totalCurrent = totalOf(current);
  console.log(`  baseline: ${totalBaseline} type error(s) across ${baselineEntries.length} file(s)`);
  console.log(`  current : ${totalCurrent} type error(s) across ${current.length} file(s)`);

  if (newFiles.length > 0) {
    console.log('');
    console.log(`FAIL: ${newFiles.length} file(s) NOT in baseline have type errors:`);
    for (const entry of newFiles) console.log(`   - ${entry}`);
  }
  if (grownFiles.length > 0) {
    console.log('');
    console.log(`FAIL: ${grownFiles.length} existing file(s) grew above their baseline count:`);
    for (const entry of grownFiles) console.log(`   - ${entry}`);
  }

  if (newFiles.length > 0 || grownFiles.length > 0) {
    console.log(`
  apps/${name} type-baseline policy
${project.note}
    - Reproduce the full list with:

        npm exec --workspace=apps/${name} -- tsc -p tsconfig.json --noEmit

    - The baseline (${project.baselineFile}) is an upper bound, not a
      target. Removals are tolerated and do NOT require regeneration; that is
      what lets clean-up PRs run in parallel. Do NOT silence a new error by
      raising its entry.
    - If you legitimately ratcheted the ceiling down (fixed existing errors) and
      want to lock the lower bound in, regenerate:

        ${regenerateCommand(name)}

      Commit the updated baseline alongside the fix.`);
    process.exit(1);
  }

  // Informational only - never fails the gate.
  if (totalCurrent < totalBaseline) {
    console.log('');
    console.log(`NOTE: baseline ceiling is ${totalBaseline - totalCurrent} error(s) higher than current.`);
    console.log('   Optional: regenerate to ratchet the ceiling down:');
    console.log(`     ${regenerateCommand(name)}`);
  }

  console.log('');
  console.log(`PASS: no new apps/${name} type errors above baseline.`);
}

function projectArg(argv) {
  const index = argv.indexOf('--project');
  if (index === -1) return 'server';
  const value = argv[index + 1];
  if (!value || value.startsWith('--')) {
    console.error('ERROR: --project needs a value (server or web)');
    process.exit(2);
  }
  return value;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const name = projectArg(process.argv);
  try {
    resolveTypeBaselineProject(name);
  } catch (error) {
    console.error(`ERROR: ${error.message}`);
    process.exit(2);
  }
  if (process.argv.includes('--regenerate')) {
    regenerate(name);
  } else {
    verify(name);
  }
}
