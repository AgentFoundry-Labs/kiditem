#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { mkdtemp, readFile, readdir, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { writeErd } from './generate-prisma-erd.mjs';

const SCHEMA_PATHS = ['prisma/schema.prisma', 'prisma/models/'];
const ERD_OVERVIEW_PATH = 'docs/ERD.md';
const DOMAIN_ERD_PATH = 'docs/erd/';

function git(args) {
  return execFileSync('git', args, { encoding: 'utf8' }).trim();
}

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 1) {
    const key = argv[i];
    if (!key.startsWith('--')) continue;
    args[key.slice(2)] = argv[i + 1];
    i += 1;
  }
  return args;
}

function changedFilesFromGit(base, head) {
  const output = git(['diff', '--name-only', `${base}...${head}`]);
  return output ? output.split('\n').filter(Boolean) : [];
}

function changedFilesFromWorkingTree() {
  return mergeChangedFiles([
    parseGitFileList(git(['diff', '--name-only'])),
    parseGitFileList(git(['diff', '--cached', '--name-only'])),
    parseGitFileList(git(['ls-files', '--others', '--exclude-standard'])),
  ]);
}

function parseGitFileList(output) {
  return output ? output.split('\n').filter(Boolean) : [];
}

export function mergeChangedFiles(groups) {
  const seen = new Set();
  const files = [];
  for (const group of groups) {
    for (const rawFile of group) {
      const file = rawFile.trim();
      if (!file || seen.has(file)) continue;
      seen.add(file);
      files.push(file);
    }
  }
  return files;
}

function matchesAnyPath(file, paths) {
  return paths.some((target) => {
    if (target.endsWith('/')) return file.startsWith(target);
    return file === target;
  });
}

export function analyzeSchemaArtifactSync(files) {
  const schemaFiles = files.filter((file) => matchesAnyPath(file, SCHEMA_PATHS));
  const requiresGeneratedArtifacts = schemaFiles.length > 0;

  return {
    schemaFiles,
    requiresGeneratedArtifacts,
  };
}

/**
 * Schema diffs are checked against generated bytes and the generated file set,
 * never against a guessed set of changed ERD paths. Some valid Prisma changes
 * (for example an index or default change) do not alter the ERD projection.
 */
export async function checkSchemaArtifactSync({
  files,
  repoRoot = process.cwd(),
  generate = writeErd,
} = {}) {
  const analysis = analyzeSchemaArtifactSync(files ?? []);
  if (!analysis.requiresGeneratedArtifacts) {
    return { ...analysis, matches: true, driftedFiles: [] };
  }

  const generated = await checkGeneratedErdArtifacts({ repoRoot, generate });
  return { ...analysis, ...generated };
}

/**
 * Regenerate ERD artifacts in an isolated temporary directory and compare
 * them with the checked-in navigation artifacts without modifying the tree.
 */
export async function checkGeneratedErdArtifacts({
  repoRoot = process.cwd(),
  generate = writeErd,
} = {}) {
  const root = path.resolve(repoRoot);
  const temporaryRoot = await mkdtemp(path.join(tmpdir(), 'kiditem-schema-artifact-sync-'));
  const outputPath = path.join(temporaryRoot, ERD_OVERVIEW_PATH);
  const domainOutputDir = path.join(temporaryRoot, DOMAIN_ERD_PATH);

  try {
    await generate({
      modelsDir: path.join(root, 'prisma', 'models'),
      outputPath,
      domainOutputDir,
    });

    const generatedFiles = [
      ERD_OVERVIEW_PATH,
      ...(await markdownFiles(domainOutputDir)).map((file) => path.posix.join('docs/erd', file)),
    ];
    const trackedDomainFiles = await markdownFiles(path.join(root, DOMAIN_ERD_PATH));
    const driftedFiles = [];

    for (const file of generatedFiles) {
      const generated = await readFile(path.join(temporaryRoot, file), 'utf8');
      const tracked = await readUtf8OrNull(path.join(root, file));
      if (tracked !== generated) driftedFiles.push(file);
    }

    for (const file of trackedDomainFiles) {
      const relativePath = path.posix.join('docs/erd', file);
      if (!generatedFiles.includes(relativePath)) driftedFiles.push(relativePath);
    }

    const uniqueDriftedFiles = [...new Set(driftedFiles)].sort((left, right) => left.localeCompare(right));
    return { matches: uniqueDriftedFiles.length === 0, driftedFiles: uniqueDriftedFiles };
  } finally {
    await rm(temporaryRoot, { recursive: true, force: true });
  }
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const base =
    args.base ||
    (process.env.GITHUB_BASE_REF ? `origin/${process.env.GITHUB_BASE_REF}` : 'origin/develop');
  const head = args.head || 'HEAD';
  const files = args.files
    ? args.files.split(',').map((file) => file.trim()).filter(Boolean)
    : mergeChangedFiles([
      changedFilesFromGit(base, head),
      changedFilesFromWorkingTree(),
    ]);

  const result = await checkSchemaArtifactSync({ files });

  if (!result.requiresGeneratedArtifacts) {
    console.log('check:schema-artifact-sync PASS — no Prisma schema change');
    return;
  }

  if (!result.matches) {
    console.error('check:schema-artifact-sync FAIL');
    console.error(`Schema files changed: ${result.schemaFiles.join(', ')}`);
    console.error(`Generated ERD drift: ${result.driftedFiles.join(', ')}`);
    console.error('Run npm run db:erd, then commit the generated ERD output.');
    process.exit(1);
  }

  console.log('check:schema-artifact-sync PASS');
  console.log(`Schema files: ${result.schemaFiles.join(', ')}`);
  console.log('Generated ERD bytes and file set are current.');
}

async function markdownFiles(directory) {
  try {
    const entries = await readdir(directory, { withFileTypes: true });
    return entries
      .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
      .map((entry) => entry.name)
      .sort((left, right) => left.localeCompare(right));
  } catch (error) {
    if (error && typeof error === 'object' && error.code === 'ENOENT') return [];
    throw error;
  }
}

async function readUtf8OrNull(filePath) {
  try {
    return await readFile(filePath, 'utf8');
  } catch (error) {
    if (error && typeof error === 'object' && error.code === 'ENOENT') return null;
    throw error;
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  void main();
}
